export type TranslationKey = string;

interface I18nContextValue {
  language: Language;
  languages: typeof LANGUAGES;
  setLanguage: (language: Language) => void;
  t: (key: TranslationKey) => string;
}

const I18nContext = React.createContext<I18nContextValue | null>(null);

function readInitialLanguage(): Language {
  const saved = localStorage.getItem(STORAGE_KEY);
  if (saved === "en" || saved === "ru" || saved === "uz") return saved;
  return "uz";
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = React.useState<Language>(readInitialLanguage);

  const setLanguage = React.useCallback((nextLanguage: Language) => {
    setLanguageState(nextLanguage);
    localStorage.setItem(STORAGE_KEY, nextLanguage);
  }, []);

  React.useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const t = React.useCallback(
    (key: TranslationKey) => {
      const active = translations[language] as Record<string, string>;
      const fallback = translations.en as Record<string, string>;
      return active[key] ?? fallback[key] ?? key;
    },
    [language]
  );

  const value = React.useMemo(
    () => ({ language, languages: LANGUAGES, setLanguage, t }),
    [language, setLanguage, t]
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = React.useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}

export function useFixedLang(lang: Language): (key: string) => string {
  return React.useCallback((key: string) => {
    const active = translations[lang];
    return active[key] ?? translations.en[key] ?? key;
  }, []); // eslint-disable-line react-hooks/exhaustive-deps
}
